const GENERIC = [
  /^inspect the component\.?$/i,
  /^fix if necessary\.?$/i,
  /^check the area\.?$/i,
  /^check the faucet\.?$/i,
  /^tighten the connection\.?$/i,
  /^test it\.?$/i,
];

function stepText(step) {
  return String(step?.instruction || step?.instructions || '').trim();
}

